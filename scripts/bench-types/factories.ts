import { MODEL_COUNT, modelAt, type BelongsTo, type ManyToMany, type Model, type Schema } from "./schema.ts";

const HEADER = "// Generated by scripts/bench-types; do not edit.";

/**
 * The control program: the generated client constructed, and nothing of this library.
 *
 * @example
 * ```ts
 * await writeFile("control.ts", renderControl());
 * ```
 */
export function renderControl(): string {
  return [
    HEADER,
    'import { PrismaBetterSqlite3 } from "@prisma/adapter-better-sqlite3";',
    'import { PrismaClient } from "./client/client.ts";',
    "",
    'export const prisma = new PrismaClient({ adapter: new PrismaBetterSqlite3({ url: ":memory:" }) });',
    "",
  ].join("\n");
}

function factoryOf(target: Model): string {
  return `${target.key}Factory`;
}

function belongsToOf(schema: Schema, current: Model): BelongsTo[] {
  return schema.relations.filter(
    (relation): relation is BelongsTo => relation.kind === "belongs-to" && relation.child === current.index,
  );
}

function definitionOf(schema: Schema, current: Model): string {
  const parents = belongsToOf(schema, current)
    .filter((relation) => relation.required)
    .map((relation) => `${relation.field}: ${factoryOf(modelAt(schema, relation.parent))}`);

  return [
    `const ${factoryOf(current)} = prismaFactorio.define("${current.key}", {`,
    `  definition: ({ uid }) => ({ ${[`${current.label}: uid`, ...parents].join(", ")} }),`,
    `  states: { renamed: { ${current.label}: "renamed" } },`,
    "});",
  ].join("\n");
}

function only<T>(found: T | undefined, what: string): T {
  if (found === undefined) throw new Error(`The synthetic schema holds no ${what}.`);
  return found;
}

function belongsToCount(schema: Schema, child: number, parent: number): number {
  return schema.relations.filter(
    (relation) => relation.kind === "belongs-to" && relation.child === child && relation.parent === parent,
  ).length;
}

// The models `holder` holds many records of, one entry per relation field, so a model reached through
// two fields appears twice.
function listTargetsOf(schema: Schema, holder: number): number[] {
  return schema.relations.flatMap((relation) => {
    if (relation.kind === "belongs-to") return relation.parent === holder ? [relation.child] : [];
    if (relation.left === holder) return [relation.right];
    return relation.right === holder ? [relation.left] : [];
  });
}

// The unnamed forms resolve the relation field from the model pair, which is the path a named field
// skips, so each model also takes one call of each where its pair shares a single relation.
function unnamedOf(schema: Schema, current: Model): string[] {
  const parent = belongsToOf(schema, current).find(
    (relation) => belongsToCount(schema, current.index, relation.parent) === 1,
  );
  const targets = listTargetsOf(schema, current.index);
  const child = targets.find((target) => targets.filter((other) => other === target).length === 1);

  return [
    ...(parent === undefined ? [] : [`.for(${factoryOf(modelAt(schema, parent.parent))})`]),
    ...(child === undefined ? [] : [`.has(${factoryOf(modelAt(schema, child))}.count(2))`]),
  ];
}

function exerciseOf(schema: Schema, current: Model): string {
  const outgoing = belongsToOf(schema, current);
  const parent = only(
    outgoing.find((relation) => relation.parent !== current.index),
    `belongs-to relation from ${current.name}`,
  );
  const self = outgoing.find((relation) => relation.parent === current.index);
  const children = only(
    schema.relations.find(
      (relation): relation is BelongsTo =>
        relation.kind === "belongs-to" &&
        relation.parent === current.index &&
        relation.child === (current.index + MODEL_COUNT - 1) % MODEL_COUNT,
    ),
    `has-many relation from ${current.name}`,
  );
  const peers = schema.relations.filter(
    (relation): relation is ManyToMany => relation.kind === "many-to-many" && relation.left === current.index,
  );

  const parentModel = modelAt(schema, parent.parent);
  const chain = [
    factoryOf(current),
    ".renamed()",
    `.for(${factoryOf(parentModel)}, "${parent.field}")`,
    ...(self === undefined ? [] : [`.for(${factoryOf(current)}, "${self.field}")`]),
    `.has(${factoryOf(modelAt(schema, children.child))}.count(2), "${children.inverse}")`,
    ...peers.map((relation) => `.has(${factoryOf(modelAt(schema, relation.right))}.count(2), "${relation.field}")`),
    ...unnamedOf(schema, current),
    `.recycle("${parentModel.key}", pooled)`,
    `.state({ ${current.label}: "inline" })`,
    `.create({ ${current.label}: "override" })`,
  ];

  return [
    `export async function exercise${current.name}(): Promise<void> {`,
    `  const pooled = await ${factoryOf(parentModel)}.create();`,
    `  await ${chain.join("\n    ")};`,
    "}",
  ].join("\n");
}

/**
 * The measured program: a factory per model of the synthetic schema, defined with a declared state,
 * then driven through `for`, `has`, `recycle`, an inline `.state()` and a `create()` override over
 * relations the schema actually holds.
 *
 * @example
 * ```ts
 * await writeFile("factories.ts", renderFactories(describeSchema()));
 * ```
 */
export function renderFactories(schema: Schema): string {
  return [
    HEADER,
    'import { initPrismaFactorio } from "../../../src/index.ts";',
    'import { prisma } from "./control.ts";',
    "",
    "const prismaFactorio = initPrismaFactorio(() => prisma);",
    "",
    ...schema.models.map((current) => definitionOf(schema, current)),
    "",
    ...schema.models.map((current) => exerciseOf(schema, current)),
    "",
  ].join("\n");
}
