import type { DMMF } from "@prisma/generator-helper";

/**
 * A file produced by the generator; `path` is relative to the generator
 * output directory.
 *
 * @example
 * const file: GeneratedFile = { path: "User.ts", content: "export class UserFactoryBase {}" };
 */
export interface GeneratedFile {
  path: string;
  content: string;
}

/**
 * Emits the factory base class file for one model.
 *
 * @example
 * emitModelFactoryFile(model).path; // "User.ts" for a model named User
 */
export function emitModelFactoryFile(model: DMMF.Model): GeneratedFile {
  const content = `// Generated by prisma-factorio. Do not edit.

export class ${model.name}FactoryBase {}
`;
  return { path: `${model.name}.ts`, content };
}

/**
 * Emits every factory base class file for the given datamodel, one per model.
 *
 * @example
 * emitFactoryFiles(options.dmmf.datamodel).map((file) => file.path); // ["User.ts", "Post.ts"]
 */
export function emitFactoryFiles(datamodel: DMMF.Datamodel): GeneratedFile[] {
  return datamodel.models.map(emitModelFactoryFile);
}
